-- Baseline: the original flat "Exams" table exactly as it exists in the live
-- project (it was created from the dashboard, so it has no migration history).
-- `if not exists` makes this a no-op against the live database; it only matters
-- when building a fresh database (local development, CI, test containers).

create table if not exists public."Exams" (
  id bigint generated by default as identity not null,
  "Course Code" text not null,
  "Course Title" text null,
  "Course Teacher" text null,
  "Class Section" text null,
  "Exam Type" text null,
  "Exam Day" text null,
  "Exam Date" timestamp without time zone null,
  "Syllabus" text null,
  "Exam Notes Drive Link" text null,
  constraint "Exams_pkey" primary key (id)
);

comment on table public."Exams" is 'Information about examination are stored in this table';

alter table public."Exams" enable row level security;
